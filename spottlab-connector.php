    const SHOP_SECTION = 'spottlab-woocommerce';

    public function __construct()
    {
        add_action('rest_api_init', [$this, 'register_routes']);
        add_filter('rest_pre_dispatch', [$this, 'never_cache'], 10, 3);
        add_filter('rest_post_dispatch', [$this, 'never_cache'], 10, 3);
        add_action('admin_menu', [$this, 'register_settings_page']);
        add_action('admin_init', [$this, 'register_settings']);
        add_action('http_api_debug', [$this, 'note_update_check'], 10, 5);
        add_filter('update_plugins_github.com', [$this, 'offer_update'], 10, 3);
        add_filter('upgrader_pre_download', [$this, 'download_update'], 10, 4);
        add_filter('upgrader_source_selection', [$this, 'keep_folder'], 10, 4);
        add_filter('plugins_api', [$this, 'plugin_information'], 10, 3);
    }

    /* ---------------------- REST route ---------------------- */

    public function register_routes()
    {
        register_rest_route(self::NAMESPACE_, '/check', [
            'methods'             => 'GET',
            'callback'            => [$this, 'handle_check'],
            'permission_callback' => [$this, 'authorize'],
        ]);
    }

    /**
     * Every answer on this route, refusals included, is for the one asking,
     * now. The token travels in a header, which page caches do not key on: a
     * cached answer would tell Spottlab "ok" while the site is down, and hand
     * the diagnostics to anyone who asks without a token. So no cache may keep
     * it — the headers for any cache that reads them, and LiteSpeed Cache's
     * own switch, since it caches the REST API by default and sets its own.
     * Before the answer, so the switch is set however early a cache decides;
     * after it, for the headers.
     */
    public function never_cache($response, $server, $request)
    {
        if (strpos($request->get_route(), '/' . self::NAMESPACE_ . '/') !== 0) {
            return $response;
        }

        if (!defined('DONOTCACHEPAGE')) {
            define('DONOTCACHEPAGE', true);
        }

        do_action('litespeed_control_set_nocache', 'Spottlab health check');

        if ($response instanceof WP_HTTP_Response) {
            $response->header('Cache-Control', 'no-store, no-cache, must-revalidate, max-age=0, private');
            $response->header('X-LiteSpeed-Cache-Control', 'no-cache');
        }

        return $response;
    }

    /**
     * Shared-secret auth via ?token= or X-Health-Token header. The token is
     * mandatory: it is generated by the Spottlab dashboard and pasted here, and
     * until that happens every request is rejected — including Spottlab's own
     * handshake, which relies on the 401 to tell "token not set up yet"
     * apart from "token accepted".
     */
    public function authorize(WP_REST_Request $request)
    {
        $configured_token = get_option(self::OPTION_TOKEN, '');

        if (empty($configured_token)) {
            return new WP_Error(
                'health_check_no_token',
                'No access token is configured. Paste the token from the Spottlab dashboard into Settings → Spottlab connector.',
                ['status' => 401]
            );
        }

        $provided = $request->get_header('x-health-token');
        if (empty($provided)) {
            $provided = $request->get_param('token');
        }

        if (!is_string($provided) || !hash_equals($configured_token, $provided)) {
            return new WP_Error(
                'health_check_bad_token',
                'Invalid access token.',
                ['status' => 401]
            );
        }

        return true;
    }

    public function handle_check(WP_REST_Request $request)
    {
        $start = microtime(true);

        $want_full      = $this->flag_requested($request, ['full', 'verbose', 'diagnostics']);
        $want_software  = $this->flag_requested($request, ['software', 'security']);
        $want_sizes     = $this->flag_requested($request, ['sizes', 'disk']);

        // Basic liveness always runs: is the page/database actually working?
        // If the mu-plugin executed, WP core + plugins + theme loaded without a
        // fatal; a quick DB ping confirms the site can serve real requests.
        $db  = $this->check_database();
        $ok  = ($db['ok'] !== false);

        $payload = [
            'status'            => $ok ? 'ok' : 'error',
            'site'              => home_url(),
            'timestamp'         => current_time('mysql', true),
            'connector_version' => self::VERSION,
        ];

        // Full diagnostic report — only when explicitly requested. Includes the
        // core/DB/disk/memory checks plus the full Site Health info (same data
        // as Tools -> Site Health -> Info).
        if ($want_full) {
            $checks = [
                'core'   => $this->check_core(),
                'db'     => $db,
                'disk'   => $this->check_disk_space(),
                'memory' => $this->check_memory(),
            ];

            foreach ($checks as $check) {
                if ($check['ok'] === false) {
                    $ok = false;
                }
            }

            // Before Site Health, which lists the updates WordPress knows of.
            // Whatever the look at WordPress.org does, the checks above stand:
            // it is not one of them, so a failed look fails nothing.
            if ($db['ok'] !== false) {
                $this->refresh_update_lists();
            }

            $payload['status']        = $ok ? 'ok' : 'error';
            $payload['checks']        = $checks;
            $payload['site_health']   = $this->site_health_report();

            // A WooCommerce shop says how its orders and payments are
            // going too, as one more section. Not one of the checks: a
            // shop with no orders is not a site that is down.
            $shop = $this->woocommerce_report();
            if ($shop !== null) {
                $payload['site_health'][self::SHOP_SECTION] = $shop;
            }
            $payload['update_checks'] = $this->update_checks_report();
        }

        // What the site runs, for Spottlab to check against known
        // vulnerabilities — only when explicitly requested.
        if ($want_software) {
            $payload['software'] = $this->software_report();
        }

        // Directory and database sizes — only when explicitly requested. These
        // are the numbers ?full=1 reports as "loading...", and they cost a
        // recursive filesystem walk, so they get their own flag.
        if ($want_sizes) {
            $payload['sizes'] = $this->sizes_report();
        }

        $payload['response_ms'] = round((microtime(true) - $start) * 1000, 2);

        $response = new WP_REST_Response($payload);
        $response->set_status($ok ? 200 : 503);

        return $response;
    }

    /**
     * True if any of the given query params is present and truthy
     * (e.g. ?full=1, ?software=true, or a bare ?full).
     */
    private function flag_requested(WP_REST_Request $request, array $names)
    {
        foreach ($names as $name) {
            if (!$request->has_param($name)) {
                continue;
            }
            $value = $request->get_param($name);
            // A bare flag (?full) arrives as an empty string — treat as true.
            if ($value === '' || $value === null) {
                return true;
            }
            if (filter_var($value, FILTER_VALIDATE_BOOLEAN, FILTER_NULL_ON_FAILURE) !== false) {
                return true;
            }
        }
        return false;
    }

    /* ---------------------- Installed software ---------------------- */

    /**
     * What the site runs: the WordPress version, and every plugin and theme by
     * its WordPress.org slug and version, active or not. Spottlab checks these
     * against public vulnerability databases itself, so nothing is scanned
     * here and no security plugin is needed.
     */
    private function software_report()
    {
        if (!function_exists('get_plugins')) {
            require_once ABSPATH . 'wp-admin/includes/plugin.php';
        }

        $plugins = [];
        foreach (get_plugins() as $file => $data) {
            // "wordpress-seo/wp-seo.php" is the plugin "wordpress-seo"; a plugin
            // that is a single file ("hello.php") is named after the file.
            $slug = strpos($file, '/') !== false ? dirname($file) : basename($file, '.php');

            $plugins[] = [
                'slug'    => $slug,
                'name'    => !empty($data['Name']) ? $data['Name'] : $slug,
                'version' => isset($data['Version']) ? (string) $data['Version'] : '',
                'active'  => is_plugin_active($file),
            ];
        }

        $themes = [];
        $in_use = [get_stylesheet(), get_template()];
        foreach (wp_get_themes() as $slug => $theme) {
            $themes[] = [
                'slug'    => $slug,
                'name'    => $theme->get('Name') ?: $slug,
                'version' => (string) $theme->get('Version'),
                // A child theme's parent is in use too.
                'active'  => in_array($slug, $in_use, true),
            ];
        }

        return [
            'core'    => ['version' => get_bloginfo('version')],
            'plugins' => $plugins,
            'themes'  => $themes,
        ];
    }

    /* ---------------------- Directory / database sizes ---------------------- */

    /**
     * Directory and database sizes, as raw bytes.
     *
     * WordPress fills these in asynchronously in wp-admin, which is why they
     * come back as "loading..." in the ?full=1 Site Health report. We compute
     * them here instead. Deliberately NOT via WP_Debug_Data::get_sizes(): that
     * has been deprecated since 5.6, and on a site with WP_DEBUG_LOG enabled it
     * would append a deprecation notice to debug.log on every poll.
     *
     * Each entry is {bytes, status}. `bytes` is null unless status is "ok".
     * Results are cached by WordPress in the `dirsize_cache` transient, so it's
     * the first walk that's expensive, not every request.
     */
    private function sizes_report()
    {
        $upload_dir = wp_get_upload_dir();

        // No trailing slashes — recurse_dirsize compares raw path strings.
        $paths = array(
            'wordpress_size' => untrailingslashit(ABSPATH),
            'themes_size'    => get_theme_root(),
            'plugins_size'   => WP_PLUGIN_DIR,
            'uploads_size'   => $upload_dir['basedir'],
        );

        if (function_exists('wp_get_font_dir')) {
            $font_dir = wp_get_font_dir();
            if (!empty($font_dir['basedir'])) {
                $paths['fonts_size'] = $font_dir['basedir'];
            }
        }

        // The WordPress total walks ABSPATH but skips the directories measured
        // separately below, so nothing is counted twice.
        $exclude = $paths;
        unset($exclude['wordpress_size']);
        $exclude = array_values($exclude);

        $budget = $this->size_time_budget();
        $report = array();
        $total  = 0;

        foreach ($paths as $name => $path) {
            if (!is_dir($path)) {
                $report[$name] = array('bytes' => 0, 'status' => 'missing');
                continue;
            }

            if (microtime(true) - WP_START_TIMESTAMP >= $budget) {
                $report[$name] = array('bytes' => null, 'status' => 'timeout');
                $total = null;
                continue;
            }

            $size = recurse_dirsize($path, ('wordpress_size' === $name ? $exclude : null), $budget);

            if (false === $size) {
                // Unreadable — usually a permissions problem.
                $report[$name] = array('bytes' => null, 'status' => 'unreadable');
                $total = null;
                continue;
            }

            if (null === $size) {
                $report[$name] = array('bytes' => null, 'status' => 'timeout');
                $total = null;
                continue;
            }

            $report[$name] = array('bytes' => (int) $size, 'status' => 'ok');

            if (null !== $total) {
                $total += (int) $size;
            }
        }

        $database = $this->database_size();

        $report['database_size'] = $database > 0
            ? array('bytes' => $database, 'status' => 'ok')
            : array('bytes' => null, 'status' => 'unavailable');

        // A total is only meaningful once every part of it is known.
        $report['total_size'] = (null !== $total && $database > 0)
            ? array('bytes' => $total + $database, 'status' => 'ok')
            : array('bytes' => null, 'status' => 'unavailable');

        return $report;
    }

    /**
     * How long the size walk may run for, in seconds. Mirrors WordPress's own
     * guard, but also caps it: a host with a very high time limit shouldn't let
     * one poll tie up a PHP worker for minutes.
     */
    private function size_time_budget()
    {
        $max = function_exists('ini_get') ? (int) ini_get('max_execution_time') : 0;

        // Defaults to 0 under CLI, and some hosts hide the value entirely.
        if ($max <= 0) {
            $max = 30;
        }

        if ($max > 20) {
            // Leave headroom so the response itself doesn't get killed.
            $max -= 2;
        }

        return min($max, 25);
    }

    /**
     * Total size of the database, in bytes.
     */
    private function database_size()
    {
        global $wpdb;

        $size = 0;
        $rows = $wpdb->get_results('SHOW TABLE STATUS', ARRAY_A);

        if ($wpdb->num_rows > 0) {
            foreach ($rows as $row) {
                $size += $row['Data_length'] + $row['Index_length'];
            }
        }

        return (int) $size;
    }

    /* ---------------------- Individual checks ---------------------- */

    private function check_core()
    {
        // If we got this far, WP core, plugins, and theme all loaded without a fatal.
        return [
            'ok'      => true,
            'message' => 'WordPress core loaded successfully.',
        ];
    }

    private function check_database()
    {
        global $wpdb;

        $result = $wpdb->get_var("SELECT 1");

        if ($result !== '1') {
            return [
                'ok'      => false,
                'message' => 'Database query failed.',
                'error'   => $wpdb->last_error,
            ];
        }

        return [
            'ok'      => true,
            'message' => 'Database connection healthy.',
        ];
    }

    private function check_disk_space()
    {
        $path = ABSPATH;
        $free  = @disk_free_space($path);
        $total = @disk_total_space($path);

        if ($free === false || $total === false || $total === 0) {
            return [
                'ok'      => true, // don't fail the whole check if the host disallows this
                'message' => 'Disk space info unavailable on this host.',
            ];
        }

        $free_percent = round(($free / $total) * 100, 1);
        $ok = $free_percent > 5.0; // alert if less than 5% free

        return [
            'ok'           => $ok,
            'free_percent' => $free_percent,
            'free_bytes'   => $free,
            'message'      => $ok ? 'Sufficient disk space.' : 'Low disk space.',
        ];
    }

    private function check_memory()
    {
        $limit_str = ini_get('memory_limit');
        $usage     = memory_get_usage(true);
        $limit_bytes = $this->to_bytes($limit_str);

        if ($limit_bytes <= 0) {
            return [
                'ok'      => true,
                'message' => 'Memory limit unbounded or unavailable.',
            ];
        }

        $usage_percent = round(($usage / $limit_bytes) * 100, 1);
        $ok = $usage_percent < 90.0;

        return [
            'ok'             => $ok,
            'usage_percent'  => $usage_percent,
            'limit'          => $limit_str,
            'message'        => $ok ? 'Memory usage normal.' : 'High memory usage.',
        ];
    }

    private function to_bytes($val)
    {
        $val = trim($val);
        if ($val === '' || $val === '-1') {
            return -1;
        }

        $unit = strtolower(substr($val, -1));
        $num  = (int) $val;

        switch ($unit) {
            case 'g': return $num * 1024 * 1024 * 1024;
            case 'm': return $num * 1024 * 1024;
            case 'k': return $num * 1024;
            default:  return $num;
        }
    }

    /* ---------------------- Site Health / diagnostics ---------------------- */

    /**
     * Full site diagnostics, mirroring Tools -> Site Health -> Info, as a
     * structured object: { section: { field: value, ... }, ... }.
     *
     * Directory/database sizes come back as "loading..." — WordPress computes
     * those asynchronously in wp-admin and we don't block the request on a
     * recursive filesystem walk here.
     */
    private function site_health_report()
    {
        $info = $this->get_debug_data();
        if ($info === null) {
            return ['available' => false, 'message' => 'Site Health data is unavailable on this WordPress version.'];
        }

        $out = [];
        foreach ($info as $section => $details) {
            // Skip empty or private sections, matching WordPress's copy output.
            if (empty($details['fields']) || !empty($details['private'])) {
                continue;
            }

            $fields = [];
            foreach ($details['fields'] as $key => $field) {
                if (!empty($field['private'])) {
                    continue;
                }
                // Prefer the concise, untranslated "debug" value when present.
                $value = array_key_exists('debug', $field) ? $field['debug'] : $field['value'];
                $fields[$key] = $this->normalize_debug_value($value);
            }
            $out[$section] = $fields;
        }

        return $out;
    }

    /**
     * Load WordPress's Site Health debug data. Requires a few wp-admin includes
     * because this runs on a front-end REST request, not in the admin: each
     * one, every time, since another plugin may have loaded the class and not
     * what it calls (file.php's get_home_path() for robots.txt, say).
     */
    private function get_debug_data()
    {
        foreach (['plugin.php', 'update.php', 'misc.php', 'file.php', 'class-wp-debug-data.php'] as $inc) {
            if (file_exists(ABSPATH . 'wp-admin/includes/' . $inc)) {
                require_once ABSPATH . 'wp-admin/includes/' . $inc;
            }
        }

        if (!class_exists('WP_Debug_Data') || !method_exists('WP_Debug_Data', 'debug_data')) {
            return null;
        }

        return WP_Debug_Data::debug_data();
    }

    /**
     * Coerce a Site Health field value into a clean JSON value, following the
     * same conventions as WordPress's text export (bools stay bool, nested
     * arrays stay one level deep, empty non-"0" values become "undefined").
     */
    private function normalize_debug_value($value)
    {
        if (is_bool($value)) {
            return $value;
        }
        if (is_array($value)) {
            $nested = [];
            foreach ($value as $k => $v) {
                $nested[$k] = is_bool($v) ? $v : (string) $v;
            }
            return $nested;
        }
        if ($value === '' || $value === null) {
            return 'undefined';
        }
        return $value;
    }

    /* ---------------------- WooCommerce ---------------------- */

    /**
     * On a WooCommerce shop: whether orders and payments are coming through,
     * and whether the shop is set up to take them. Counts, times, settings
     * and the names of gateways and template files only: never an order,
     * what was in it, what it came to, or who placed it.
     *
     * Null where WooCommerce is not active. Each part is read on its own and
     * left out if WooCommerce cannot give it (an older version, an extension
     * in the way), so one that fails costs the report nothing else, and
     * Spottlab reads a figure that is missing as not known.
     */
    private function woocommerce_report()
    {
        if (!class_exists('WooCommerce') || !function_exists('WC') || !function_exists('wc_get_orders')) {
            return null;
        }

        $report = ['version' => defined('WC_VERSION') ? (string) WC_VERSION : 'undefined'];

        foreach (['shop_setup', 'shop_gateways', 'shop_orders', 'shop_queue', 'shop_templates', 'shop_stock', 'shop_webhooks'] as $part) {
            try {
                $report = array_merge($report, (array) $this->{$part}());
            } catch (Throwable $e) {
                // Left out.
            }
        }

        return $report;
    }

    /**
     * Whether the shop is open and whole: WooCommerce's own database update
     * waiting after a plugin update, "coming soon" mode (9.1+), and the pages
     * a shop cannot do without.
     */
    private function shop_setup()
    {
        $out = [];

        if (class_exists('WC_Install') && is_callable(['WC_Install', 'needs_db_update'])) {
            $out['database_update_needed'] = (bool) WC_Install::needs_db_update();
        }

        $soon = get_option('woocommerce_coming_soon', null);
        if (is_string($soon) && $soon !== '') {
            $out['coming_soon'] = $soon === 'yes';
        }

        if (function_exists('wc_get_page_id')) {
            $missing = [];
            foreach (['shop', 'cart', 'checkout', 'myaccount'] as $page) {
                $id = (int) wc_get_page_id($page);
                if ($id < 1 || get_post_status($id) !== 'publish') {
                    $missing[] = $page;
                }
            }
            $out['pages_missing'] = $missing;
        }

        return $out;
    }

    /**
     * The payment gateways switched on, by id, and those of them that say
     * they are in test or sandbox mode. Gateways keep that setting each in
     * its own way, so this asks the usual ones: a guess that can miss a
     * gateway, never one that names a live gateway as testing.
     */
    private function shop_gateways()
    {
        $gateways = WC()->payment_gateways();
        if (!is_object($gateways) || !method_exists($gateways, 'payment_gateways')) {
            return [];
        }

        $enabled = [];
        $testing = [];

        foreach ((array) $gateways->payment_gateways() as $gateway) {
            if (!is_object($gateway) || !isset($gateway->enabled) || $gateway->enabled !== 'yes' || empty($gateway->id)) {
                continue;
            }

            $enabled[] = (string) $gateway->id;

            if ($this->gateway_is_testing($gateway)) {
                $testing[] = (string) $gateway->id;
            }
        }

        return ['gateways_enabled' => $enabled, 'gateways_in_test_mode' => $testing];
    }

    private function gateway_is_testing($gateway)
    {
        if (isset($gateway->testmode) && in_array($gateway->testmode, [true, 'yes', '1', 1], true)) {
            return true;
        }

        if (!method_exists($gateway, 'get_option')) {
            return false;
        }

        foreach (['testmode', 'test_mode', 'sandbox', 'sandbox_on', 'sandbox_mode', 'test_mode_enabled'] as $key) {
            if (in_array($gateway->get_option($key, ''), [true, 'yes', '1', 1, 'on'], true)) {
                return true;
            }
        }

        foreach (['environment', 'mode'] as $key) {
            if (in_array($gateway->get_option($key, ''), ['test', 'testing', 'sandbox'], true)) {
                return true;
            }
        }

        return false;
    }

    /**
     * How orders are going, in numbers and times (UTC): when the last one
     * came through, how many did and how many failed in the last day (the
     * failed by gateway), and how many are waiting in each state with since
     * when the oldest has been. An order "came through" once it is paid for
     * or awaiting a payment made elsewhere: processing, on hold, completed.
     */
    private function shop_orders()
    {
        $through = ['processing', 'on-hold', 'completed'];
        $since   = '>' . (time() - DAY_IN_SECONDS);
        $out     = [];

        $last = wc_get_orders(['type' => 'shop_order', 'status' => $through, 'limit' => 1, 'orderby' => 'date', 'order' => 'DESC']);
        $out['last_order_at'] = $this->order_time(is_array($last) && $last ? reset($last) : null);
        $out['orders_24h']    = $this->order_count(['status' => $through, 'date_created' => $since]);

        $failed  = (array) wc_get_orders(['type' => 'shop_order', 'status' => ['failed'], 'date_created' => $since, 'limit' => 200, 'orderby' => 'date', 'order' => 'DESC']);
        $by_gate = [];
        foreach ($failed as $order) {
            $gateway = is_object($order) && method_exists($order, 'get_payment_method') ? (string) $order->get_payment_method() : '';
            $gateway = $gateway !== '' ? $gateway : 'unknown';
            $by_gate[$gateway] = (isset($by_gate[$gateway]) ? $by_gate[$gateway] : 0) + 1;
        }
        $out['orders_failed_24h']            = count($failed);
        $out['orders_failed_24h_by_gateway'] = $by_gate;

        foreach (['pending', 'on-hold', 'processing'] as $status) {
            $key    = 'orders_' . str_replace('-', '_', $status);
            $oldest = wc_get_orders(['type' => 'shop_order', 'status' => [$status], 'limit' => 1, 'orderby' => 'date', 'order' => 'ASC']);

            $out[$key]                = $this->order_count(['status' => [$status]]);
            $out[$key . '_oldest_at'] = $this->order_time(is_array($oldest) && $oldest ? reset($oldest) : null);
        }

        return $out;
    }

    private function order_count(array $args)
    {
        $found = wc_get_orders(array_merge(['type' => 'shop_order', 'limit' => 1, 'paginate' => true, 'return' => 'ids'], $args));

        return is_object($found) && isset($found->total) ? (int) $found->total : 'undefined';
    }

    private function order_time($order)
    {
        if (!is_object($order) || !method_exists($order, 'get_date_created')) {
            return 'undefined';
        }

        $created = $order->get_date_created();

        return is_object($created) && method_exists($created, 'getTimestamp') ? gmdate('Y-m-d H:i:s', $created->getTimestamp()) : 'undefined';
    }

